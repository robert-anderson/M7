/*
 * Inherits from FillerPureRDM and adds a function to print out all contributing pairs of MBF contributing * to a
 * RDM instead of just adding the contribution. These are ordered in a std::set to allow comparison with the reference
 * data from * python irrespective of the ordering of the generated pairs.
 */
struct FillerTestPureRdm : public PureRdm {
    suite::Mbfs m_work_mbfs;
    struct Result {
        uintv_t m_abra, m_bbra, m_aket, m_bket;
        bool operator < (const Result& other) const {
            /**
             * not the true lexicographic ordering operator of two size_t vecs, but good enough to uniquely order a set
             */
            auto lt_v = [](const uintv_t& v1, const uintv_t& v2) -> bool {
                if (v1.size() < v2.size()) return true;
                if (v1.size() > v2.size()) return false;
                return std::memcmp(v1.data(), v2.data(), v1.size() * sizeof(uint_t)) < 0;
            };
            // try to decide order by abra
            if (m_abra != other.m_abra) return (lt_v(m_abra, other.m_abra));
            // order couldn't be decided by abra, move on to bbra
            if (m_bbra != other.m_bbra) return (lt_v(m_bbra, other.m_bbra));
            // order couldn't be decided by bbra, move on to aket
            if (m_aket != other.m_aket) return (lt_v(m_aket, other.m_aket));
            // order couldn't be decided by aket, move on to bket
            if (m_bket != other.m_bket) return (lt_v(m_bket, other.m_bket));
            // order couldn't be decided by bket, so results are actually equal
            return false;
        }

        bool operator ==(const Result& other) const {
            return (m_abra == other.m_abra) && (m_bbra == other.m_bbra) && (m_aket == other.m_aket) && (m_bket == other.m_bket);
        }

    };
    std::set<Result> m_gen_strings;

    FillerTestPureRdm(const conf::Rdms& opts, OpSig ranksig, sys::Sector sector) :
        PureRdm(opts, ranksig, sector, 1, "test_rdm"), m_work_mbfs(sector){}

protected:

    static void fill_setbits_vec(uintv_t& v, const field::FrmOnvSpinChannel& spin_channel) {
        v.clear();
        auto fn = [&v](uint_t ibit) { v.push_back(ibit);};
        spin_channel.foreach_setbit(fn);
    }

    void frm_make_contribs(const FrmOnv &src_onv, const conn::FrmOnv &conn, const com_ops::Frm &, wf_t) override {
        buffered::FrmOnvSpinChannel spin_channel(src_onv.m_basis.m_nsite);
        auto& dst_onv = m_work_mbfs[src_onv];
        conn.apply(src_onv, dst_onv);

        Result res;
        src_onv.copy_alpha_to(spin_channel);
        fill_setbits_vec(res.m_abra, spin_channel);
        src_onv.copy_beta_to(spin_channel);
        fill_setbits_vec(res.m_bbra, spin_channel);
        dst_onv.copy_alpha_to(spin_channel);
        fill_setbits_vec(res.m_aket, spin_channel);
        dst_onv.copy_beta_to(spin_channel);
        fill_setbits_vec(res.m_bket, spin_channel);

        m_gen_strings.emplace(std::move(res));
    }
};

